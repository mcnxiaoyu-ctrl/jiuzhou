/**
 * AI 生成超时共享配置
 *
 * 作用（做什么 / 不做什么）：
 * 1) 做什么：集中维护 AI 生成类链路的统一超时阈值，覆盖文本生成任务、图片生成请求与生成任务 worker 超时。
 * 2) 不做什么：不创建计时器、不发起请求，也不处理超时后的退款、状态流转或错误提示。
 *
 * 输入 / 输出：
 * - 输入：无。
 * - 输出：`AI_GENERATION_TIMEOUT_MS`，表示 AI 生成相关功能统一超时毫秒数。
 *
 * 数据流 / 状态流：
 * 共享超时常量 -> 业务专用超时别名 / 模型配置默认值 -> worker 池任务超时 / SDK 请求超时 / fetch AbortController。
 *
 * 复用设计说明：
 * 1) 洞府研修、伙伴招募、云游奇遇与图片生成都属于用户等待 AI 生成结果的链路，统一从这里读取超时，避免多处硬编码 30 分钟。
 * 2) 各业务模块可以保留语义化别名，但数值来源必须回到本模块，后续调整只改这一个入口。
 * 3) “AI 生成超时”是高频业务变化点，集中后可避免 worker 外层和模型内层超时不一致造成任务状态分叉。
 *
 * 关键边界条件与坑点：
 * 1) 单位固定为毫秒，调用方不得再自行做分钟或秒到毫秒的二次换算。
 * 2) 这里只覆盖 AI 生成类等待链路，不能复用到数据库连接、敏感词审核、市场风控等非 AI 生成超时。
 */
export const AI_GENERATION_TIMEOUT_MS = 30 * 60 * 1000;
